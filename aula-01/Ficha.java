/*
Ficha.java — imprima uma ficha sua em 4 linhas (nome, cidade, curso e um objetivo para o curso), 
usando println. Depois reescreva a mesma saída usando um único System.out.println com \n;
*/

public class Ficha {
	public static void main(String[] args) {
		System.out.println("Clayton Santana Nunciatto");
		System.out.println("Hortolândia");
		System.out.println("Ciências da computação");
		System.out.println("Aprender a programar");

		System.out.println();

		System.out.println("Agora segue tudo em uma só linha de comando:\n \nClayton Santana Nunciatto \nHortolândia \nCiências da computação \nAprender a programar");				

	}
}